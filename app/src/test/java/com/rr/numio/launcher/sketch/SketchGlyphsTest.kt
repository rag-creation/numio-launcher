package com.rr.numio.launcher.sketch

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/** The design rules from art/sketch-icons/glyphs.py, checked on the data the app ships. */
class SketchGlyphsTest {

    private fun paths(layers: List<Layer>) = layers.mapNotNull {
        when (it) {
            is Layer.Fill -> it.path
            is Layer.Ink -> it.path
            is Layer.Thin -> it.path
            is Layer.Hatch -> it.path
            is Layer.Dot -> null
        }
    }

    @Test fun everyPrototypeAppHasASymbol() {
        assertEquals(SketchKind.entries.toSet(), SketchGlyphs.all.keys)
        for ((k, layers) in SketchGlyphs.all) assertTrue("$k has no pen line", layers.any { it is Layer.Ink || it is Layer.Thin })
    }

    @Test fun pathsUseOnlyMoveLineCurveClose() {
        for ((k, layers) in SketchGlyphs.all) for (p in paths(layers)) {
            assertTrue("$k: $p", Regex("^[MLCZ0-9.,\\s-]+$").matches(p))
            assertTrue("$k starts with M", p.trimStart().startsWith("M"))
        }
    }

    @Test fun everySymbolSharesOneSize() {
        // content stays inside 22..78 on the 100 grid (a little slack for curve handles and caps)
        for ((k, layers) in SketchGlyphs.all) {
            val nums = paths(layers).flatMap { Regex("-?\\d+(?:\\.\\d+)?").findAll(it).map { m -> m.value.toFloat() }.toList() } +
                layers.filterIsInstance<Layer.Dot>().flatMap { listOf(it.x - it.r, it.x + it.r, it.y - it.r, it.y + it.r) }
            assertTrue("$k goes outside its box: ${nums.min()}..${nums.max()}", nums.min() >= 20f && nums.max() <= 80f)
        }
    }

    @Test fun goldStaysAnAccentAndHatchingStaysSmall() {
        for ((k, layers) in SketchGlyphs.all) {
            val gold = layers.count {
                (it is Layer.Thin && it.tone == Tone.GOLD) || (it is Layer.Dot && it.tone == Tone.GOLD) ||
                    (it is Layer.Fill && it.tone == Tone.GOLD)
            }
            assertTrue("$k uses gold $gold times", gold <= 2)
            assertTrue("$k has more than one hatch", layers.count { it is Layer.Hatch } <= 1)
            for (h in layers.filterIsInstance<Layer.Hatch>()) {
                assertTrue("$k hatch has more than 4 strokes", h.path.count { it == 'M' } <= 4)
            }
        }
    }

    @Test fun appDataMatchesTheDesignSource() {
        // Unit tests run from app/: the generator writes the same strings it holds
        val src = File("../art/sketch-icons/glyphs.py").readText()
        assertTrue(src.contains("SketchGlyphs.kt"))
        val kt = File("src/main/java/com/rr/numio/launcher/sketch/SketchGlyphs.kt").readText()
        assertTrue(kt.contains("Generated by art/sketch-icons/glyphs.py"))
        for (k in SketchKind.entries) assertTrue("${k.name} missing in generator", src.contains("GLYPHS[\"${k.name.lowercase()}\"]"))
    }
}
